// The browser file system of one match (client/engine/vfs.js): every file the
// engine may open, the URL it is fetched from, and the generated select.def.
// Engine files live under data/engine/fs/, packs under the public routes.
import { stageMusicOverrides } from './stage-music.js';

export function buildFsManifest(catalog) {
  const engine = catalog.engine();
  if (!engine) return null;
  const files = catalog.files();
  return {
    engine: {
      wasm: engine.wasm,
      loader: engine.loader,
      version: engine.version,
      replayProtocol: engine.replayProtocol,
      audioProtocol: engine.audioProtocol,
      startupProtocol: engine.startupProtocol,
      sessionProtocol: engine.sessionProtocol,
    },
    groups: [
      { prefix: '', base: '/games/mugen/engine/fs/', files: engine.files },
      { prefix: 'chars/', base: '/mugen/', files: files.characters },
      { prefix: 'stages/', base: '/mugen-stages/', files: files.stages },
    ],
    generated: { 'data/select.def': selectDef(catalog), ...stageMusicOverrides(catalog) },
  };
}

/** The roster the engine's own screens would show; quick matches name files directly. */
export function selectDef(catalog) {
  const lines = ['; Generated by the ChaOS MUGEN add-on from games/mugen/data/.', '[Characters]'];
  for (const character of catalog.characters()) lines.push(character.path);
  lines.push('', '[ExtraStages]');
  for (const stage of catalog.stages()) lines.push('stages/' + stage.path);
  lines.push('', '[Options]', '');
  return lines.join('\n');
}
